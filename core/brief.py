"""Write docs/product_brief.md with every figure pulled from the database (python -m core.brief)."""
import json

from core import analytics, config, db, metrics, notes, reconcile, risk


def build(con, truth=None):
    a = config.assumptions()
    _, auth = metrics.value(con, "auth_rate")
    _, succ = metrics.value(con, "success_rate")
    _, cps = metrics.value(con, "cost_per_settled")
    res = con.execute("SELECT * FROM recon_results").df()
    brk = con.execute("SELECT * FROM recon_exceptions").df()
    s = reconcile.summary(res, brk)
    _, buckets, curve, opt = risk.analyse(con)
    cur = risk.at_threshold(curve, a["risk"]["current_threshold"])
    t_base, sens = risk.sensitivity(buckets)
    rec, _ = risk.recommendation(opt, cur, risk.costs(), t_base, sens)
    _, rules = risk.rules_comparison(con, opt["threshold"])
    earners = rules[rules["net_saving_on_top_of_score"] > 0]
    rule_text = "; ".join(f"**{r.rule.lower()}** adds {r.extra_fraud_caught_vs_score} caught frauds for "
                          f"{r.extra_genuine_blocked_vs_score} extra blocked customers" for r in earners.itertuples())
    rule_text = (f"Rules that earn their keep on top of the score: {rule_text}. The other "
                 f"{len(rules) - len(earners)} mostly re-catch what the score already sees and add friction."
                 if len(earners) else "No rule earns its keep on top of the score; each adds more friction than it saves.")
    single = sens.iloc[:4].assign(abs_shift=sens["shift"].abs())
    top = single.sort_values("abs_shift", ascending=False).iloc[0]
    ins = notes.build_insights(con)
    n_pay = con.execute("SELECT count(*) FROM payments").fetchone()[0]
    _, _, clusters = analytics.detect_settle_clusters(con)

    findings = "\n".join(f"{i}. **{n['title']}.** {n['note']}  \n   *Story:* {n['story']}"
                         for i, n in enumerate(ins, 1))
    by_type = ", ".join(f"{r.break_type.replace('_', ' ')} {r.breaks:,}" for r in s["by_type"].itertuples())
    scoring = ""
    if truth:
        sc = reconcile.score_against_truth(con, brk, truth)
        scoring = (f" Against the planted answer key it found {sc['recall']:.0%} of breaks, classified "
                   f"{sc['classification_accuracy']:.0%} correctly, and flagged {sc['false_positives']} clean payments.")

    return f"""# Product brief: Payment Performance & Risk Control Tower

*For a payments squad. Synthetic data: {n_pay:,} payments from 20,000 customers over six months on card, Faster Payments,
Bacs credit and direct debit. Every cost and rate is an assumption in `config/assumptions.yaml`. Generated by
`python -m core.brief`; every figure below comes from a DuckDB query.*

## Problem
Payments teams lose time to the same four questions: why payments fail, where our records disagree with the scheme,
what each rail costs, and how hard to lean on fraud controls. Each is usually answered in a different tool with a
different definition. This project answers all four from one dataset with one metric registry, and ends on a decision.

## Users
Payments product owners (what to fix first), operations and finance (which breaks to work), fraud and risk (where to set
the threshold), and analysts (one definition per metric, SQL always visible).

## Where we stand
Authorisation rate **{auth:.2%}**, end-to-end success **{succ:.2%}** (retries counted against the original),
cost per settled payment **£{cps:.3f}**. Reconciliation matches **{s['match_rate']:.2%}** of settled payments; **{s['breaks']:,}**
breaks hold **£{s['value_at_risk']:,.0f}** at risk ({by_type}). **{s['timing_differences']:,}** timing differences were
correctly *not* raised as breaks.{scoring}

## Four findings
{findings}

## Fraud threshold recommendation
{rec}

{rule_text}

## Assumptions to challenge first
1. **Cost inputs (£{a['risk']['false_decline_cost_gbp']} per false decline, amount plus £{a['risk']['fraud_loss_extra_gbp']} per missed fraud).** The biggest single move is "{top['scenario']}", which shifts the optimum by {top['shift']:+.3f}; get real margin, churn and chargeback data.
2. **Fraud labels.** Here they are complete and instant. Real labels arrive weeks late and are incomplete, which biases the curve.
3. **Rail costs.** Cost per payment figures are invented; confirm scheme and processor pricing before acting on the cost drift.

## What I would do first with real data
1. Rebuild the cost curve on confirmed fraud with label dates, and re-run it monthly.
2. Put the reconciliation passes on one real scheme file for a week and compare its queue with the ops team's manual breaks.
3. Agree the metric registry definitions with the squads before building any further dashboards.
"""


def main():
    con = db.connect(read_only=True)
    truth = json.load(open(config.TRUTH_PATH)) if config.TRUTH_PATH.exists() else None
    text = build(con, truth)
    out = config.ROOT / "docs" / "product_brief.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out} ({len(text.split())} words)")


if __name__ == "__main__":
    main()
